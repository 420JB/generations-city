/**
 * Derive transparent copies of the supplied Rare Friends family SVGs.
 *
 * The canonical sources in public/assets/families/ carry an explicit full-canvas black
 * <rect>. This script removes ONLY that element and writes the result to
 * public/assets/families/transparent/ with the same file name. The Friend <path>
 * geometry is copied byte-for-byte; nothing is rasterised. Sources are never modified.
 *
 * It also writes src/config/familyArtMetrics.ts: the silhouette bounding box of every
 * asset (in the 512×512 viewBox), used to seat the T5 statue's feet on its plinth.
 *
 * Usage: node scripts/derive-transparent-families.mjs
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SRC = 'public/assets/families'
const OUT = join(SRC, 'transparent')

/** Matches a self-closing <rect> with width/height/fill attributes in any order. */
const RECT = /<rect\b[^>]*\/>/g

function attr(tag, name) {
  const m = tag.match(new RegExp(`\\b${name}="([^"]*)"`))
  return m ? m[1] : null
}

function isBlack(fill) {
  return fill !== null && ['#000', '#000000', 'black'].includes(fill.toLowerCase())
}

export function deriveTransparent(svg) {
  const root = svg.match(/<svg\b[^>]*>/)
  if (!root) throw new Error('no <svg> root')
  const vb = (attr(root[0], 'viewBox') ?? '').split(/\s+/).map(Number)
  if (vb.length !== 4) throw new Error('missing viewBox')
  const [vx, vy, vw, vh] = vb
  const backgrounds = [...svg.matchAll(RECT)].filter(([tag]) => {
    const x = Number(attr(tag, 'x') ?? 0)
    const y = Number(attr(tag, 'y') ?? 0)
    return x === vx && y === vy && Number(attr(tag, 'width')) === vw && Number(attr(tag, 'height')) === vh && isBlack(attr(tag, 'fill'))
  })
  if (backgrounds.length !== 1) throw new Error(`expected exactly one full-canvas black rect, found ${backgrounds.length}`)
  const out = svg.replace(backgrounds[0][0], '')
  if (/<rect\b/.test(out)) throw new Error('unexpected extra <rect> left behind')
  return out
}

/** Bounding box of the white Friend path, in viewBox units. */
export function silhouetteBounds(svg) {
  const path = svg.match(/<path\b[^>]*\/>/)
  if (!path) throw new Error('no <path>')
  const t = (attr(path[0], 'transform') ?? '').match(/translate\(([-\d.]+)[ ,]+([-\d.]+)\)\s*scale\(([-\d.]+)\)/)
  if (!t) throw new Error('unexpected path transform')
  const [tx, ty, k] = t.slice(1).map(Number)
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity
  for (const m of attr(path[0], 'd').matchAll(/M([\d.]+) ([\d.]+)h([\d.]+)v([\d.]+)H[\d.]+Z/g)) {
    const [x, y, w, h] = m.slice(1).map(Number)
    x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x + w); y1 = Math.max(y1, y + h)
  }
  return { x0: tx + x0 * k, y0: ty + y0 * k, x1: tx + x1 * k, y1: ty + y1 * k }
}

const files = readdirSync(SRC).filter((f) => f.endsWith('.svg')).sort()
mkdirSync(OUT, { recursive: true })
for (const f of files) {
  const src = readFileSync(join(SRC, f), 'utf8')
  const out = deriveTransparent(src)
  const paths = (s) => [...s.matchAll(/<path\b[^>]*\/>/g)].map((m) => m[0]).join('\n')
  if (paths(src) !== paths(out)) throw new Error(`${f}: path geometry changed`)
  writeFileSync(join(OUT, f), out)
  console.log(`${f}: ${src.length} -> ${out.length} bytes`)
}
console.log(`Derived ${files.length} transparent SVGs into ${OUT}`)

const metrics = {}
for (const f of files) {
  const [, key, v] = f.match(/^([a-z]+)-(\d)\.svg$/)
  metrics[key] ??= {}
  metrics[key][v] = silhouetteBounds(readFileSync(join(SRC, f), 'utf8'))
}
const rows = Object.entries(metrics).map(
  ([key, vs]) => `  ${key}: {\n${Object.entries(vs).map(([v, b]) => `    ${v}: { x0: ${b.x0}, y0: ${b.y0}, x1: ${b.x1}, y1: ${b.y1} },`).join('\n')}\n  },`,
)
writeFileSync(
  'src/config/familyArtMetrics.ts',
  `// GENERATED by scripts/derive-transparent-families.mjs. Do not edit by hand.
import type { FamilyKey } from './districtIdentity'

export interface SilhouetteBounds {
  x0: number
  y0: number
  x1: number
  y1: number
}

/** Friend silhouette bounds per family asset, in the assets' 512×512 viewBox. */
export const FAMILY_ART_VIEWBOX = 512
export const FAMILY_ART_METRICS: Record<FamilyKey, Record<1 | 2, SilhouetteBounds>> = {
${rows.join('\n')}
}
`,
)
console.log('Wrote src/config/familyArtMetrics.ts')
