-- World core: the durable identity of a brand's city and what that city has been told by
-- Proofy Play.
--
-- A world is one persistent city for one Discord server's installation of this game. This
-- migration records only facts that cannot change with later product decisions:
--   worlds                  which city row a world is;
--   world_play_bindings     which Play installation (environment, game, guild) the world belongs to;
--   world_config_versions   copies of the Play configuration versions the world has seen, each
--                           with the verdict this game gave it (accepted or rejected);
--   world_config_adoptions  the order in which accepted versions came to govern the world.
--
-- Structure only. Nothing here creates a world, a city, a binding or a configuration, and
-- nothing here changes an existing row: the Rare Friends city, its properties, eras, intents
-- and events are left exactly as they are. No service route reads these tables yet.
--
-- A world's city is not a Rare Friends city. The legacy activation tables (0004) keep
-- working for the Rare Friends city and are refused for any world's city. One rule is added
-- to every city: at sequence 1 it changes only by advancing (city_world_founding_guard).
--
-- Deliberately absent: districts, collections, layouts, assignment or allocation state, and
-- anything about trials or plans. A world's identity is its installation, which Play keeps
-- across suspension, uninstall, reinstall and a change of plan; nothing here depends on plan.
--
-- Constraints in this file are permanent (migrations never drop one), so table CHECKs state
-- only shape. Rules that are policy live in guard functions, which a later migration can
-- replace.
--
-- The guards are row triggers. TRUNCATE, disabling triggers and DDL that rewrites a table
-- (which gives every row a new row version) are table-owner powers that they do not cover;
-- against those, a deployed database relies on the service connecting as a role that does
-- not own these tables, and on backups. The privileges such a role needs are listed at the
-- end of this file.

-- Creating triggers on app_meta, city, activation_intents and properties and foreign keys to city
-- takes brief locks on live tables. If one cannot be had quickly, fail and roll back rather
-- than queue readers behind this migration; the deploy can simply be run again.
SET LOCAL lock_timeout = '10s';

-- ---------------------------------------------------------------------------------------
-- worlds: one city row per world, for good
-- ---------------------------------------------------------------------------------------

CREATE TABLE worlds (
  -- Generated by the application (UUIDv7). Never reused, never changed.
  id               uuid        PRIMARY KEY,
  city_id          text        NOT NULL,
  city_instance_id uuid        NOT NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT worlds_city           FOREIGN KEY (city_id, city_instance_id) REFERENCES city (id, instance_id),
  -- A city row belongs to at most one world.
  CONSTRAINT worlds_one_per_city   UNIQUE (city_id)
);

COMMENT ON TABLE worlds IS 'One persistent city per Play installation of this game. Immutable and never removed, in every environment.';

-- A world is founded on a city that may hold real properties, installed (sequence 1) in the
-- same transaction as the world and its Play binding. It never changes and is never removed,
-- in any environment: its identity must outlive trials, upgrades and reinstalls everywhere,
-- not only in production.
--
-- Founding the city in the same transaction is what keeps the Rare Friends activation tables
-- out of a world's city without a race: no other transaction can see the city until the
-- world is committed with it, and from then on the legacy guards see the world. The checks
-- below for legacy records read this transaction's snapshot, so they are only a second line:
-- the guarantee is that nobody else could ever have seen the city.
--
-- The proof of "inserted in this transaction" is that the city row version visible here was
-- written by this transaction's top level (its xmin). On its own that would also be true of an
-- existing city this transaction has merely updated, however trivially. That is ruled out by
-- city_world_founding_guard below: a city at sequence 1 cannot be updated without moving to
-- sequence 2, and 0004 never lets a sequence go back, so a city at sequence 1 whose row this
-- transaction wrote is one this transaction inserted. A city inserted inside a savepoint
-- carries the savepoint's own transaction id and is refused: insert it at the top level.
--
-- The row lock below conflicts with the lock the legacy guards take on the city, so the two
-- also queue on each other.
--
-- The Rare Friends city ("main") is not a world: it keeps its own tables and rules. Should it
-- ever be registered as one, that is a deliberate later migration replacing this function.
CREATE FUNCTION worlds_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    RAISE EXCEPTION 'a world is permanent: it cannot be changed';
  END IF;
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'a world is permanent: it cannot be removed';
  END IF;

  IF NEW.city_id = 'main' THEN
    RAISE EXCEPTION 'the Rare Friends city is not a world';
  END IF;
  -- Refused here rather than left to the foreign key, which is only checked when the statement ends.
  PERFORM 1 FROM city c WHERE c.id = NEW.city_id AND c.instance_id = NEW.city_instance_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'a world needs its city to exist first (foreign key worlds -> city)' USING ERRCODE = 'foreign_key_violation';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM city c WHERE c.id = NEW.city_id AND (c.canonical OR c.activation_rehearsal)) THEN
    RAISE EXCEPTION 'a world can only be a canonical or rehearsal city';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM city c WHERE c.id = NEW.city_id AND c.sequence = 1) THEN
    RAISE EXCEPTION 'a world is founded on a newly installed city: an existing city cannot be taken over';
  END IF;
  -- Written by this transaction at sequence 1, and therefore inserted by it (see above).
  IF NOT EXISTS (SELECT 1 FROM city c WHERE c.id = NEW.city_id AND c.xmin = pg_current_xact_id()::xid) THEN
    RAISE EXCEPTION 'a world is founded on a city installed in the same transaction: an existing city cannot be taken over';
  END IF;
  IF EXISTS (SELECT 1 FROM activation_intents i WHERE i.city_id = NEW.city_id)
     OR EXISTS (SELECT 1 FROM properties p WHERE p.city_id = NEW.city_id) THEN
    RAISE EXCEPTION 'a city that holds Rare Friends activation records cannot become a world';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER worlds_guard
  BEFORE INSERT OR UPDATE OR DELETE ON worlds
  FOR EACH ROW EXECUTE FUNCTION worlds_guard();

-- A city at sequence 1 changes only by advancing to sequence 2. 0004 already keeps what a city
-- is, and its state, fixed while the sequence stands still; this also refuses an update that
-- changes nothing, or only a timestamp. Such an update would give an existing city a row
-- version written by the updating transaction, which worlds_guard would otherwise take for a
-- city that transaction had just installed. The service only ever updates a city to advance it.
--
-- Named to fire after the 0004 city guards, so their refusals are reported first.
CREATE FUNCTION city_world_founding_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.sequence = 1 AND NEW.sequence = 1 THEN
    RAISE EXCEPTION 'a city at sequence 1 changes only by advancing its sequence';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER city_world_founding_guard
  BEFORE UPDATE ON city
  FOR EACH ROW EXECUTE FUNCTION city_world_founding_guard();

-- ---------------------------------------------------------------------------------------
-- The Rare Friends activation tables (0004) never name a world's city
-- ---------------------------------------------------------------------------------------

-- 0004 lets an intent or a property name any canonical or rehearsal city, and every world's
-- city is one. A Friend is one property across all cities (p_one_per_friend), so without
-- this a Friend placed in a world's city would also be refused in the Rare Friends city.
--
-- The city row is locked first with the same lock mode the foreign key to city takes when the
-- statement ends (FOR KEY SHARE), so this adds no new lock order to the activation path. It
-- does add a privilege: the foreign key locks as the table owner, but this guard locks as the
-- writer, and any row lock needs UPDATE on at least one column of the table locked (see the
-- end of this file). Writing an intent or a property now also needs SELECT on worlds.
-- Only inserts are checked: 0004 already keeps an intent's and a property's city permanent.
CREATE FUNCTION legacy_activation_world_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  PERFORM 1 FROM city c WHERE c.id = NEW.city_id FOR KEY SHARE;
  IF EXISTS (SELECT 1 FROM worlds w WHERE w.city_id = NEW.city_id) THEN
    RAISE EXCEPTION 'a world''s city holds no Rare Friends activation records (%)', TG_TABLE_NAME;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER activation_intents_world_guard
  BEFORE INSERT ON activation_intents
  FOR EACH ROW EXECUTE FUNCTION legacy_activation_world_guard();

CREATE TRIGGER properties_world_guard
  BEFORE INSERT ON properties
  FOR EACH ROW EXECUTE FUNCTION legacy_activation_world_guard();

-- ---------------------------------------------------------------------------------------
-- world_play_bindings: which Play installation a world belongs to
-- ---------------------------------------------------------------------------------------

CREATE TABLE world_play_bindings (
  world_id             uuid        PRIMARY KEY REFERENCES worlds (id),
  -- Play's own environment names (dev, test, staging, live). See world_play_bindings_guard
  -- for which of them a database of each environment may hold.
  play_environment     text        NOT NULL,
  -- Play's game key, in Play's own shape.
  play_game_key        text        NOT NULL,
  play_installation_id uuid        NOT NULL,
  discord_guild_id     text        NOT NULL,
  bound_at             timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT wpb_environment_known CHECK (play_environment IN ('dev', 'test', 'staging', 'live')),
  CONSTRAINT wpb_game_key_shape    CHECK (play_game_key ~ '^[a-z][a-z0-9-]{1,62}[a-z0-9]$'),
  CONSTRAINT wpb_guild_id_shape    CHECK (discord_guild_id ~ '^[0-9]{15,25}$'),
  -- An installation is one world.
  CONSTRAINT wpb_one_per_installation UNIQUE (play_environment, play_installation_id),
  -- A Discord server has at most one city of this game.
  CONSTRAINT wpb_one_per_guild     UNIQUE (play_environment, play_game_key, discord_guild_id),
  -- Lets configuration copies name the installation of their own world, and no other.
  CONSTRAINT wpb_world_installation UNIQUE (world_id, play_installation_id)
);

COMMENT ON TABLE world_play_bindings IS 'Immutable world -> Play installation mapping, never removed in any environment. A reinstall or a change of plan keeps the installation, and so the world.';

-- A binding is written once, with its world, for the Play environment this database serves:
--   production -> live, staging -> staging, local -> dev or test; an unstamped database none.
-- It never changes and is never removed, in any environment: not on a reinstall, not on a
-- change of plan.
--
-- The stamp row is read FOR SHARE, so a concurrent change of the stamp either commits first
-- (and is seen here, or ends a REPEATABLE READ transaction with a serialization failure) or
-- waits for this transaction and then sees its binding (app_meta_world_guard). That lock is
-- taken as the writer, so writing a binding needs UPDATE on a column of app_meta (see the end
-- of this file).
CREATE FUNCTION world_play_bindings_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  stamp text;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    RAISE EXCEPTION 'a world binding is permanent: its world, environment, game, installation and guild cannot change';
  END IF;
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'a world binding is permanent: it cannot be removed';
  END IF;

  SELECT m.value INTO stamp FROM app_meta m WHERE m.key = 'environment' FOR SHARE;
  IF NOT COALESCE(CASE stamp
                    WHEN 'production' THEN NEW.play_environment = 'live'
                    WHEN 'staging'    THEN NEW.play_environment = 'staging'
                    WHEN 'local'      THEN NEW.play_environment IN ('dev', 'test')
                  END, false) THEN
    RAISE EXCEPTION 'a world binding must be for the Play environment this database serves (production: live; staging: staging; local: dev or test)';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER world_play_bindings_guard
  BEFORE INSERT OR UPDATE OR DELETE ON world_play_bindings
  FOR EACH ROW EXECUTE FUNCTION world_play_bindings_guard();

-- Checked when the transaction commits: a world never exists without its binding, so every
-- world is reachable from exactly one installation. (Neither can be removed afterwards.)
CREATE FUNCTION world_require_binding() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM world_play_bindings b WHERE b.world_id = NEW.id) THEN
    RAISE EXCEPTION 'a world cannot exist without its Play binding';
  END IF;
  RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER worlds_require_binding
  AFTER INSERT ON worlds
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION world_require_binding();

-- The environment stamp decides which bindings a database may hold, so once it holds any the
-- stamp cannot move. (app_meta_guard in 0004 already keeps a production stamp for good.)
--
-- The stamp may only be changed in a READ COMMITTED transaction. There, this check runs once
-- the stamp row is locked and sees every binding committed by then; a binding still being
-- written holds that row FOR SHARE, so this waits for it. A REPEATABLE READ or SERIALIZABLE
-- transaction would check against its older snapshot and could miss that binding.
CREATE FUNCTION app_meta_world_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.key = 'environment'
     AND (TG_OP = 'DELETE' OR NEW.key IS DISTINCT FROM OLD.key OR NEW.value IS DISTINCT FROM OLD.value) THEN
    IF current_setting('transaction_isolation') <> 'read committed' THEN
      RAISE EXCEPTION 'the environment stamp can only be changed in a READ COMMITTED transaction';
    END IF;
    IF EXISTS (SELECT 1 FROM world_play_bindings) THEN
      RAISE EXCEPTION 'a database that holds world bindings keeps its environment stamp';
    END IF;
  END IF;
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER app_meta_world_guard
  BEFORE UPDATE OR DELETE ON app_meta
  FOR EACH ROW EXECUTE FUNCTION app_meta_world_guard();

-- ---------------------------------------------------------------------------------------
-- world_config_versions: copies of Play configuration versions, with this game's verdict
-- ---------------------------------------------------------------------------------------

-- What the database proves, and what it does not:
--   * proved: config_hash is the SHA-256 of config_canonical, and the text is one JSON object;
--   * NOT proved: that config_canonical is Play's canonical form, or that config_hash is the
--     hash Play published. Any JSON text whose hash matches itself is accepted.
--
-- Play serves a configuration as a parsed JSON value and publishes configHash = SHA-256 (as
-- lowercase hex) of canonicalJson(config) encoded as UTF-8, where canonicalJson
-- (@proofy/play-contract, packages/contract/src/canonical.ts) sorts object keys by UTF-16
-- code unit, keeps array order, writes numbers and strings exactly as JSON.stringify does,
-- emits no whitespace and drops undefined members. The importer that writes this table MUST
-- canonicalize the parsed config with that exact algorithm, MUST compare the result's
-- hash with the configHash Play served, and MUST refuse the version if they differ, before
-- inserting. Postgres cannot do this for it: jsonb orders keys differently and normalizes
-- numbers.
CREATE TABLE world_config_versions (
  world_id             uuid        NOT NULL,
  -- Play's version number for this installation (1, 2, 3 ...). Play's versions are immutable.
  version              integer     NOT NULL,
  -- The installation that served it: always this world's own (see wcv_world_installation).
  play_installation_id uuid        NOT NULL,
  -- Play's config-schema version the document was written against.
  schema_version       integer     NOT NULL,
  -- Lowercase hex SHA-256 of config_canonical as UTF-8. Equal to Play's configHash only if the
  -- importer stored Play's canonical text (see above).
  config_hash          text        NOT NULL,
  -- Play's canonical JSON text of the configuration, as produced by the importer, byte for
  -- byte (text, not json/jsonb, so nothing is reordered or reformatted).
  config_canonical     text        NOT NULL,
  -- This game's judgement of the document. Final for this version: Play never changes a
  -- version, so a corrected configuration arrives as a new one.
  verdict              text        NOT NULL,
  -- Why a rejected version was refused. Absent for an accepted one.
  rejection            jsonb,
  -- What judged it (validator name and version), for later audit.
  judged_by            text        NOT NULL,
  recorded_at          timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (world_id, version),
  CONSTRAINT wcv_world_installation FOREIGN KEY (world_id, play_installation_id) REFERENCES world_play_bindings (world_id, play_installation_id),
  CONSTRAINT wcv_version_positive   CHECK (version >= 1),
  CONSTRAINT wcv_schema_positive    CHECK (schema_version >= 1),
  CONSTRAINT wcv_hash_shape         CHECK (config_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT wcv_config_is_object   CHECK (json_typeof(config_canonical::json) = 'object'),
  CONSTRAINT wcv_verdict_known      CHECK (verdict IN ('accepted', 'rejected')),
  CONSTRAINT wcv_rejection_shape    CHECK ((verdict = 'rejected') = (rejection IS NOT NULL)
                                           AND (rejection IS NULL OR jsonb_typeof(rejection) = 'object')),
  CONSTRAINT wcv_judged_by_shape    CHECK (char_length(judged_by) BETWEEN 1 AND 100)
);

COMMENT ON TABLE world_config_versions IS 'Immutable copies of the Play configuration versions a world has seen, each accepted or rejected by this game. The database checks config_hash against config_canonical; that the text is Play''s canonical form is the importer''s duty.';

-- A copy's hash must be the SHA-256 of its stored text, and the text no larger than Play's
-- contract allows. It is written once and never changed; in production never removed.
CREATE FUNCTION world_config_versions_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    RAISE EXCEPTION 'a configuration version is permanent: it cannot be changed';
  END IF;
  IF TG_OP = 'DELETE' THEN
    IF rc_database_is_production() THEN
      RAISE EXCEPTION 'a configuration version is permanent: a production copy cannot be removed';
    END IF;
    RETURN OLD;
  END IF;

  -- Play's contract limit (LIMITS.configBytes, 64 KiB) on the canonical JSON text as UTF-8.
  -- Play's own database allows 1.5 times that, but only for its jsonb rendering, which adds
  -- separators; the canonical text here is held to the contract limit itself.
  IF octet_length(NEW.config_canonical) > 65536 THEN
    RAISE EXCEPTION 'a configuration version is larger than Play allows (64 KiB of canonical JSON)';
  END IF;
  IF encode(sha256(convert_to(NEW.config_canonical, 'UTF8')), 'hex') <> NEW.config_hash THEN
    RAISE EXCEPTION 'a configuration version must match its hash: config_hash is the SHA-256 of config_canonical';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER world_config_versions_guard
  BEFORE INSERT OR UPDATE OR DELETE ON world_config_versions
  FOR EACH ROW EXECUTE FUNCTION world_config_versions_guard();

-- ---------------------------------------------------------------------------------------
-- world_config_adoptions: which accepted version governs a world, and from when
-- ---------------------------------------------------------------------------------------

-- Append-only. Adoption n+1 replaces adoption n as the governing configuration. The same
-- version may be adopted again later (Play can re-activate an earlier version), so versions
-- are not unique here and need not increase.
CREATE TABLE world_config_adoptions (
  world_id     uuid        NOT NULL,
  adoption_seq integer     NOT NULL,
  version      integer     NOT NULL,
  adopted_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (world_id, adoption_seq),
  CONSTRAINT wca_version         FOREIGN KEY (world_id, version) REFERENCES world_config_versions (world_id, version),
  CONSTRAINT wca_seq_positive    CHECK (adoption_seq >= 1)
);

COMMENT ON TABLE world_config_adoptions IS 'Append-only order in which accepted configuration versions came to govern a world.';

-- Adoptions are numbered 1, 2, 3 ... per world, and only an accepted version is adopted.
-- Never changed; in production never removed.
CREATE FUNCTION world_config_adoptions_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    RAISE EXCEPTION 'world_config_adoptions is append-only: an adoption cannot be changed';
  END IF;
  IF TG_OP = 'DELETE' THEN
    IF rc_database_is_production() THEN
      RAISE EXCEPTION 'world_config_adoptions is append-only: a production adoption cannot be removed';
    END IF;
    RETURN OLD;
  END IF;

  -- Refused here rather than left to the foreign key, which is only checked when the statement ends.
  IF NOT EXISTS (SELECT 1 FROM world_config_versions v WHERE v.world_id = NEW.world_id AND v.version = NEW.version) THEN
    RAISE EXCEPTION 'an adoption needs its configuration version to exist first (foreign key world_config_adoptions -> world_config_versions)' USING ERRCODE = 'foreign_key_violation';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM world_config_versions v WHERE v.world_id = NEW.world_id AND v.version = NEW.version AND v.verdict = 'accepted') THEN
    RAISE EXCEPTION 'only an accepted configuration version can be adopted';
  END IF;
  IF NEW.adoption_seq <> 1 + COALESCE((SELECT max(a.adoption_seq) FROM world_config_adoptions a WHERE a.world_id = NEW.world_id), 0) THEN
    RAISE EXCEPTION 'adoptions are numbered consecutively from 1 for each world';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER world_config_adoptions_guard
  BEFORE INSERT OR UPDATE OR DELETE ON world_config_adoptions
  FOR EACH ROW EXECUTE FUNCTION world_config_adoptions_guard();

-- ---------------------------------------------------------------------------------------
-- The guards read real tables, never a session's temporary ones (as in 0004)
-- ---------------------------------------------------------------------------------------

DO $$
DECLARE
  guard text;
BEGIN
  FOREACH guard IN ARRAY ARRAY[
    'worlds_guard()', 'city_world_founding_guard()', 'legacy_activation_world_guard()', 'world_play_bindings_guard()', 'world_require_binding()',
    'app_meta_world_guard()', 'world_config_versions_guard()', 'world_config_adoptions_guard()'
  ] LOOP
    EXECUTE format('ALTER FUNCTION %I.%s SET search_path = %I, pg_temp', current_schema(), guard, current_schema());
  END LOOP;
END;
$$;

-- ---------------------------------------------------------------------------------------
-- Privileges a role that does not own these tables needs
-- ---------------------------------------------------------------------------------------

-- The guards run with the privileges of whoever writes, not of the table owner (none is
-- SECURITY DEFINER). Foreign key checks still run as the owner and need nothing. Beyond
-- INSERT on the rows it writes, a writing role needs:
--   * a row lock (FOR UPDATE, FOR SHARE, FOR KEY SHARE) needs UPDATE on at least one column
--     of the table locked. A column-level grant on a column that carries no rule is enough,
--     and grants no power over the columns that matter:
--       city      locked by worlds_guard (FOR UPDATE) and legacy_activation_world_guard
--                 (FOR KEY SHARE). A role that already advances the city holds this.
--       app_meta  locked by world_play_bindings_guard (FOR SHARE). UPDATE (created_at) is
--                 enough; never grant UPDATE on key or value to a runtime role, since the
--                 environment stamp is what every guard trusts.
--   * SELECT on every table a guard reads:
--       provisioning a world   city, activation_intents, properties (worlds_guard), app_meta
--                              (world_play_bindings_guard), world_play_bindings
--                              (world_require_binding);
--       adopting a config      world_config_versions, world_config_adoptions;
--       a legacy intent/property   additionally worlds (legacy_activation_world_guard).
-- A role holding UPDATE on any column of a table can also row-lock that table's rows, and so
-- delay other writers; that is a nuisance, not a way past any rule here.
-- Changing the environment stamp needs UPDATE (or DELETE) on app_meta's key and value, and is
-- an operator action, never a runtime one.
